from pathlib import Path

ROOT = Path('.')


def read(path):
    return (ROOT / path).read_text(encoding='utf-8')


def write(path, text):
    text = text.rstrip() + '\n'
    (ROOT / path).write_text(text, encoding='utf-8')


def replace_once(text, old, new, label):
    if old not in text:
        raise SystemExit(f'missing expected text: {label}')
    if text.count(old) != 1:
        raise SystemExit(f'non-unique expected text: {label} count={text.count(old)}')
    return text.replace(old, new, 1)


def append_once(path, marker, block):
    text = read(path)
    if marker in text:
        raise SystemExit(f'already present: {marker}')
    write(path, text.rstrip() + '\n\n' + block.strip() + '\n')


